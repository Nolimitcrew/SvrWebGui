package modbus

// CRC16 вычисляет контрольную сумму Modbus RTU (CRC-16/MODBUS).
//
// Алгоритм (из спецификации "Modbus over Serial Line"):
//   - полином 0xA001 — это отражённый (reversed) полином 0x8005;
//   - начальное значение регистра 0xFFFF;
//   - каждый байт обрабатывается поразрядно — 8 сдвигов;
//   - в кадр сумма суммируется младшим байтом вперёд (little-endian).
//
// Сумма покрывает адрес устройства и весь PDU, но не саму себя.
//
// Функция понадобится реализации RTUTransport: при передаче добавлять
// CRC к кадру, при приёме — проверять его. Сейчас живёт здесь, рядом
// с протоколом, чтобы не прятать магию в недрах конкретного транспорта.
func CRC16(data []byte) uint16 {
	crc := uint16(0xFFFF)
	for _, b := range data {
		crc ^= uint16(b) // смешиваем текущий байт в младшую часть регистра
		for i := 0; i < 8; i++ {
			if crc&0x0001 != 0 {
				crc = (crc >> 1) ^ 0xA001
			} else {
				crc >>= 1
			}
		}
	}
	return crc
}
