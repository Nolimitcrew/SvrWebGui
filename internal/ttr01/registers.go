// Package ttr01 реализует драйвер контроллера отопления и ГВС TTR-01.
//
// Драйвер построен поверх абстракции modbus.Transport, поэтому с одним и
// тем же кодом он может работать как с Serial RTU, так и с Modbus TCP —
// достаточно подменить объект транспорта.
package ttr01

// Адреса и параметры регистров TTR-01.
//
// В Modbus области holding-регистров носятся префиксом «4»: 40001 = регистру 0.
// Поэтому Modbus-адрес 43101 = регистр 43101 - 40001 = 3100 = 0x0C1C,
// что совпадает с адресом, указанным в задаче.
const (
	// RegCurrentDataStart — начало области «текущие данные» (Modbus 43101).
	RegCurrentDataStart uint16 = 43101 - 40001

	// RegCurrentDataCount — сколько регистров читать одним запросом.
	// 32 регистра охватывают все поля текущей структуры с небольшим запасом.
	RegCurrentDataCount uint16 = 32

	// CurrentDataMinRegisters — минимум регистров, необходимый для
	// заполнения структуры CurrentData.
	CurrentDataMinRegisters int = 17
)

// Смещения полей внутри области «текущие данные», считаются относительно
// RegCurrentDataStart и измеряются в регистрах.
//
// ВНИМАНИЕ (для архитектора проекта): смещения уточняются по карте регистров
// TTR-01 из руководства по эксплуатации. Текущие значения — рабочая
// гипотеза, позволяющая уже сейчас протестировать весь путь
// «драйвер → транспорт → разбор». Исправить их достаточно в одном месте —
// и остальной код сразу подстроится.
const (
	OffTOutdoor uint16 = 0  // уличная температура      (2 регистра)
	OffTIndoor  uint16 = 2  // комнатная температура     (2 регистра)
	OffTSupply  uint16 = 4  // температура подачи        (2 регистра)
	OffTReturn  uint16 = 6  // температура обратки       (2 регистра)
	OffTDHW     uint16 = 8  // температура ГВС           (2 регистра)
	OffStatus   uint16 = 10 // флаги состояния           (1 регистр)
	OffYear     uint16 = 11 // время прибора
	OffMonth    uint16 = 12
	OffDay      uint16 = 13
	OffHour     uint16 = 14
	OffMinute   uint16 = 15
	OffSecond   uint16 = 16
)

// Флаги состояния — биты регистра по смещению OffStatus.
//
// ВНИМАНИЕ: значения-точки уточняются по документации прибора.
const (
	// StatusHeating — включено отопление.
	StatusHeating uint16 = 1 << 0
	// StatusDHW — включено нагрев горячего водоснабжения (ГВС).
	StatusDHW uint16 = 1 << 1
	// StatusPump — насос циркуляции работает.
	StatusPump uint16 = 1 << 2
	// StatusAlarm — аварийная ситуация.
	StatusAlarm uint16 = 1 << 3
)
